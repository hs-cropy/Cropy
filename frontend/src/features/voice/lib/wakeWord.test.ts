import { describe, expect, it } from "vitest";
import { matchWakeWord } from "./wakeWord";

describe("matchWakeWord", () => {
  it.each([
    ["크로피", ""],
    ["크로피야", ""],
    ["크로피야 이거 무슨 병이야", "이거 무슨 병이야"],
    ["크로피, 약 얼마나 타", "약 얼마나 타"],
    ["어 크로삐 사진 찍어 줘", "사진 찍어 줘"],
    ["그로피 님 안녕", "안녕"],
    // 2026-11-11 실제 녹음에서 SenseVoice가 적은 형태
    ["그렇피？", ""],
    ["그費？ 그록피 이거 진단해줘.", "이거 진단해줘."],
    ["피.", ""],
    ["그로피. 그로피.", ""],
    ["그로페 이거 찍어봐.", "이거 찍어봐."],
    ["그피.", ""],
    ["록피.", ""],
    ["야, 크로피 약 얼마나 타", "약 얼마나 타"],
    ["록끼. 이거 무슨 병 걸린 거야?", "이거 무슨 병 걸린 거야?"],
    ["로피？", ""],
    ["그로피 그만 하자.", "그만 하자."],
  ])("%s → 이어진 말 %s", (text, remainder) => {
    expect(matchWakeWord(text)).toEqual({ remainder, by: "name" });
  });

  it.each([
    ["야", ""],
    ["야 이거 무슨 병이야", "이거 무슨 병이야"],
    ["저기요 사진 찍어 줘", "사진 찍어 줘"],
    ["여보세요", ""],
    ["이봐 이거 뭐야", "이거 뭐야"],
    ["선생님 이거 무슨 병이야", "이거 무슨 병이야"],
    ["안녕", ""],
  ])("부르는 말 %s → 이어진 말 %s", (text, remainder) => {
    expect(matchWakeWord(text)).toEqual({ remainder, by: "call" });
  });

  it.each(["이거 무슨 병이야", "오늘 날씨 좋다", "크로마키 켜 줘", "", "병이야", "이거 야 뭐야", "야채 심었어", "얘기 좀 하자", "피해가 커요", "그 피해는"])(
    "호출어 없음: %s",
    (text) => {
      expect(matchWakeWord(text)).toBeNull();
    },
  );
});
